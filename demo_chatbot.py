# -*- coding: utf-8 -*-
"""
Day 1 第一段代码：规则版"聊天搭子"

目标：不调用任何 AI，只用最基础的 Python 做一个会回应你的程序。
为什么从这里开始？因为 AI 陪伴 Agent 的本质就是"输入一句话 → 输出一句话"，
先用规则把这条链路跑通，后面换成大模型时，你会立刻明白它替代了哪一部分。

【今天会学到的 5 个知识点】
1. print / input      —— 程序的输出和输入
2. 变量与字符串        —— 记住信息（比如你的名字）
3. 字典 dict          —— 关键词 → 回复的映射表
4. 函数 def           —— 把一段逻辑封装起来复用
5. while 循环         —— 让程序一直聊下去，直到你说再见
"""

# ============ 1. 知识库：关键词 → 回复 ============
# 这是一个字典，冒号左边是"触发词"，右边是"回复内容"
# 想扩展她的话题，直接往这里加新行就行
REPLIES = {
    "你好": "你好呀，今天过得怎么样？",
    "累": "听起来今天挺辛苦的。要不要跟我说说，是什么让你觉得累？",
    "开心": "那真好，我跟着一起开心。发生什么好事了？",
    "难过": "我在呢。想说的时候，慢慢说就好。",
    "再见": "那先聊到这儿，记得好好吃饭。",
    "晚安": "晚安，做个好梦。",
}


# ============ 2. 函数：根据你的一句话，决定她要回什么 ============
def reply(text, name):
    """接收你说的话，返回她要说的话。"""

    # 如果她知道了你的名字，就先"认一下人"（这是最简单的"记忆"雏形）
    if name:
        prefix = f"{name}，"
    else:
        prefix = ""

    # 遍历字典里的每一个关键词，看看你说的话里有没有出现
    for keyword, answer in REPLIES.items():
        if keyword in text:
            return prefix + answer

    # 一个关键词都没命中时的兜底回复
    return prefix + "嗯，我在听。你可以多说一点吗？"


# ============ 3. 主程序：开始对话 ============
def main():
    print("=" * 40)
    print("  小星：很高兴见到你（输入 退出 结束对话）")
    print("=" * 40)

    name = ""  # 先用一个空字符串占个位置，等她记住你的名字

    while True:  # 无限循环：一直聊天，直到 break
        text = input("\n你：").strip()  # 读入你说的话，去掉首尾空格

        if text == "退出":
            print("小星：好，下次再聊。")
            break  # 跳出循环，程序结束

        # —— 最简单的"记忆"：从"我叫XXX"里把你的名字提取出来 ——
        if text.startswith("我叫"):
            name = text[2:]  # 从第 2 个字符开始截取，也就是"我叫"后面的部分
            print(f"小星：{name}，我记住了。")
            continue  # 记住名字后直接进入下一轮

        # —— 正常回复 ——
        print("小星：" + reply(text, name))


# 这一行是 Python 的固定写法：只有直接运行本文件时，才执行 main()
if __name__ == "__main__":
    main()
