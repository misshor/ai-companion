# ============================================================
# 任务 1 · 分数评价（必做）
# 要求：
#   输入分数 -> 90+ 优秀 / 75-89 良好 / 60-74 及格 / 60 以下 不及格
# 注意：
#   1. input 拿到的是字符串，要 int() 转成数字才能比较大小
#   2. elif 的顺序：从高到低，别写反
# 测完这 4 个值：95 / 89 / 60 / 30
# ============================================================

# 在这里写你的代码
num = input("输入分数")
age = int(num)
if age >= 90:
    print("优秀")
elif age >= 75:
    print("良好")
elif age >= 60:
    print("及格")
else:
    print("不及格")
# ============================================================
# 任务 2 · 情绪识别（必做）
# 要求：
#   输入一句话，根据包含的关键词给不同回应
#   含"累"   -> 听起来今天挺辛苦的。
#   含"开心" -> 那真好，快说说发生了什么？
#   含"难过" -> 我在呢，想说的时候慢慢说。
#   都不含   -> 嗯，我在听。你可以多说一点。
# 提示：用 "关键词" in 变量 作为条件
# ============================================================

# 在这里写你的代码
sentence = input("说一句话")
if "累" in sentence :
    print("听起来今天挺辛苦的")
elif "开心" in sentence :
    print("那真好，快说说发生了什么")
elif "难过" in sentence  :
    print("我在呢，想说的时候慢慢说。")
else :
    print("嗯，我在听。你可以多说一点")
